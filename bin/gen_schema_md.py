#!/usr/bin/env python3
"""
Generate SCHEMA.md from a built lake's manifest.json plus the column
dictionaries in parquet_transform.py (COLUMN_DESCRIPTIONS, COLUMN_SOURCES,
COLUMN_TYPES, TABLE_META).

One section per table: description, keys, sort order, partitioning, then a
column table (column | type | category | source path | description).  Ends
with the schema versioning policy (plan H.4).

Usage:
    python bin/gen_schema_md.py --lake demo/lake/2026_01/lake -o SCHEMA.md
"""

import os
import sys
import json
import argparse

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from parquet_transform import (  # noqa: E402
    COLUMN_DESCRIPTIONS, COLUMN_SOURCES, COLUMN_TYPES, TABLE_META, SCHEMA_VERSION,
)

VERSIONING_POLICY = """## Versioning policy

The schema version (`schema_version` in `manifest.json`, `version` in `datapackage.json`, and the `schema_version` key in every Parquet footer) is a semver that is independent of the UniProt data release; a data release normally ships with an unchanged schema.

- **Major:** any column renamed, removed, retyped or reordered; any table renamed or removed; partition or sort-order change; a change in NULL/empty-list convention.
- **Minor:** a column or table added; an enum gaining a value; a new manifest key.
- **Patch:** a bug fix that changes values without changing the schema, compression or file-size changes, documentation.
- The UniProt data release (`2026_03`) and the schema version are independent; a data release normally ships with an unchanged schema.

`manifest.json` also carries an integer `version`: the manifest *format* version, bumped only when the manifest's own structure changes.
"""


def _md_escape(text: str) -> str:
    return text.replace("|", "\\|")


def render(manifest: dict) -> str:
    out = []
    out.append(f"# UniProtKB Parquet lake — schema {manifest.get('schema_version', SCHEMA_VERSION)}\n")
    out.append(f"Generated by `bin/gen_schema_md.py` from a `{manifest.get('release')}` build "
               f"(manifest format version {manifest.get('version')}). "
               "Column names, types and order are frozen at this schema version; see the policy at the end.\n")
    out.append("## Tables\n")
    out.append("| Table | Rows in this build | Description |")
    out.append("| --- | --- | --- |")
    for name, info in manifest["tables"].items():
        out.append(f"| `{name}` | {info['row_count']:,} | {_md_escape(info.get('description', ''))} |")
    out.append("")

    for name, info in manifest["tables"].items():
        meta = TABLE_META.get(name, {})
        cats = meta.get("columns", {})
        out.append(f"## `{name}`\n")
        out.append(info.get("description", "") + "\n")
        out.append(f"- Primary key: `{', '.join(info.get('primary_key', []))}`")
        fks = info.get("foreign_keys") or {}
        if fks:
            out.append("- Foreign keys: " + ", ".join(f"`{k}` → `{v}`" for k, v in fks.items()))
        out.append(f"- Sort order: `{', '.join(info.get('sort_order') or [])}`")
        part = info.get("partitioning")
        if part:
            keys = ", ".join(f"`{k['name']}={'|'.join(k.get('values', []))}`" for k in part.get("keys", []))
            out.append(f"- Partitioning: {part.get('scheme')} by {keys}")
        out.append("")
        out.append("| Column | Type | Category | Source path | Description |")
        out.append("| --- | --- | --- | --- | --- |")
        for col in info["columns"]:
            cname = col["name"]
            key = (name, cname)
            category = ("convenience" if cname in cats.get("convenience", [])
                        else "nested" if cname in cats.get("nested", []) else "")
            ctype = COLUMN_TYPES.get(key, col["type"])
            out.append("| `{}` | `{}` | {} | {} | {} |".format(
                cname, _md_escape(ctype), category,
                f"`{COLUMN_SOURCES[key]}`" if key in COLUMN_SOURCES else "derived",
                _md_escape(COLUMN_DESCRIPTIONS.get(key, ""))))
        out.append("")

    out.append(VERSIONING_POLICY)
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser(description="Generate SCHEMA.md from a lake manifest")
    parser.add_argument("--lake", required=True, help="Lake directory containing manifest.json")
    parser.add_argument("-o", "--output", default="SCHEMA.md")
    args = parser.parse_args()
    with open(os.path.join(args.lake, "manifest.json")) as f:
        manifest = json.load(f)
    text = render(manifest)
    with open(args.output, "w") as f:
        f.write(text)
    print(f"Wrote {args.output} ({len(manifest['tables'])} tables)", file=sys.stderr)


if __name__ == "__main__":
    main()
