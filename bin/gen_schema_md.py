#!/usr/bin/env python3
"""
Generate SCHEMA.md for one release from its lake's manifest.json plus the
column dictionaries in parquet_transform.py (COLUMN_DESCRIPTIONS,
COLUMN_SOURCES, TABLE_META), through its column_* helpers.

Types are the ones this build actually wrote: shortcut columns always carry
their declared type, source columns (UniProt's JSON keys) the type inferred
from this release's input.  The PROVENANCE step of upjson2lake.nf
publishes the result beside the lake as <release>/SCHEMA.md.

One section per table: description, keys, sort order, partitioning, then a
column table (column | type | category | source path | description).  Ends
with the schema versioning policy.

Usage:
    python bin/gen_schema_md.py --lake <release>/lake -o SCHEMA.md
"""

import os
import sys
import json
import argparse

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from parquet_transform import (  # noqa: E402
    COLUMN_SOURCES, SCHEMA_VERSION, _source_path, _split_top, column_categories,
    column_description,
)

VERSIONING_POLICY = """## Versioning policy

The schema version (`schema_version` in `manifest.json`, `version` in `datapackage.json`, and the `schema_version` key in every Parquet footer) is a semver of the **shortcut** columns and the layout: the tables, their sort orders and partitioning, and the shortcut columns' names and types. It is independent of the UniProt data release; a data release normally ships with an unchanged schema version.

- **Major:** a shortcut column renamed, removed or retyped; a table renamed or removed; a partition or sort-order change; a change in the NULL / empty-list convention.
- **Minor:** a shortcut column or a table added; a new manifest key.
- **Patch:** a bug fix that changes values without changing the schema; compression or file-size changes; documentation.

Source columns are UniProt's JSON keys, named and typed as each release ships them, so they are not versioned: when UniProt adds, removes or retypes a field, the source column that holds it appears, disappears or changes type. The release's `validation_report.txt` lists every such difference from the previous release (check 14).

`manifest.json` also carries an integer `version`: the manifest *format* version, bumped only when the manifest's own structure changes.
"""




def _display_type(type_str: str, limit: int = 120) -> str:
    """A nested type too long for a table cell becomes its top-level field
    list, e.g. ``struct<allergenName, alternativeNames, ...>`` (a field name
    containing ", " or a bracket is misread: see _split_top)."""
    if len(type_str) <= limit:
        return type_str
    head, _, body = type_str.partition("<")
    inner = body[:-1]
    if head in ("list", "large_list"):
        # list<child: T>, the child named l (DuckDB), item (PyArrow) or element
        return f"{head}<{_display_type(inner.partition(': ')[2], limit)}>"
    if head != "struct":
        return type_str[:limit - 3] + "..."
    return f"struct<{', '.join(p.partition(': ')[0] for p in _split_top(inner))}>"


def _md_escape(text: str) -> str:
    return text.replace("|", "\\|")


def render(manifest: dict) -> str:
    out = []
    out.append(f"# UniProtKB Parquet lake — schema {manifest.get('schema_version', SCHEMA_VERSION)}\n")
    out.append(f"Generated by `bin/gen_schema_md.py` from the `{manifest.get('release')}` build "
               f"(manifest format version {manifest.get('version')}).\n")
    out.append("Two kinds of column: **shortcut** columns (snake_case) have fixed names and declared "
               "types, the same in every build of this schema version; **source** columns are the "
               "table's UniProt JSON element, one per key, named as in UniProt's JSON and typed as "
               "this release's input. Long nested types are shown as their top-level fields; "
               "`manifest.json` has the full types. See the versioning policy at the end.\n")
    out.append("## Tables\n")
    out.append("| Table | Rows in this build | Description |")
    out.append("| --- | --- | --- |")
    for name, info in manifest["tables"].items():
        out.append(f"| `{name}` | {info['row_count']:,} | {_md_escape(info.get('description', ''))} |")
    out.append("")

    for name, info in manifest["tables"].items():
        shortcuts = set(column_categories(name, [c["name"] for c in info["columns"]])["shortcut"])
        out.append(f"## `{name}`\n")
        out.append(info.get("description", "") + "\n")
        if info.get("primary_key"):
            out.append(f"- Primary key: `{', '.join(info['primary_key'])}`")
        fks = info.get("foreign_keys") or {}
        if fks:
            # One key per referenced table: (accession, organism_id) together
            # identify the entry; organism_id alone is not a key.
            by_target: dict[str, list[tuple[str, str]]] = {}
            for column, ref in fks.items():
                ref_table, _, ref_column = ref.partition(".")
                by_target.setdefault(ref_table, []).append((column, ref_column))
            out.append("- Foreign keys: " + "; ".join(
                f"`({', '.join(c for c, _ in pairs)})` → `{t}({', '.join(r for _, r in pairs)})`"
                for t, pairs in by_target.items()))
        out.append(f"- Sort order: `{', '.join(info.get('sort_order') or [])}`")
        part = info.get("partitioning")
        if part:
            keys = ", ".join(f"`{k['name']}={'|'.join(k.get('values', []))}`" for k in part.get("keys", []))
            out.append(f"- Partitioning: {part.get('scheme')} by {keys}")
        out.append("")
        out.append("| Column | Type | Category | Source path | Description |")
        out.append("| --- | --- | --- | --- | --- |")
        for col in info["columns"]:
            cname = col["name"]
            key = (name, cname)
            if cname in shortcuts:
                category = "shortcut"
                source = f"`{COLUMN_SOURCES[key]}`" if key in COLUMN_SOURCES else "derived"
            else:
                category, source = "source", f"`{_source_path(name, cname)}`"
            ctype = _display_type(col["type"])
            out.append("| `{}` | `{}` | {} | {} | {} |".format(
                cname, _md_escape(ctype), category, _md_escape(source),
                _md_escape(column_description(name, cname))))
        out.append("")

    out.append(VERSIONING_POLICY)
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser(description="Generate SCHEMA.md from a lake manifest")
    parser.add_argument("--lake", required=True, help="Lake directory containing manifest.json")
    parser.add_argument("-o", "--output", default="SCHEMA.md")
    args = parser.parse_args()
    with open(os.path.join(args.lake, "manifest.json")) as f:
        manifest = json.load(f)
    text = render(manifest)
    with open(args.output, "w") as f:
        f.write(text)
    print(f"Wrote {args.output} ({len(manifest['tables'])} tables)", file=sys.stderr)


if __name__ == "__main__":
    main()
